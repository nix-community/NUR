"""Validation gate for the qompassai/NUR repository.

This is Qompass AI's fork of the nix-community NUR registry.
Its content is the registry itself — repos.json (581 community
repositories), repos.json.lock, and the upstream ci/ tooling —
plus one load-bearing entry: qompassai, registering
github.com/qompassai/nur-packages.

Upstream's own gate is ci/test.sh. Its first half (mypy, black,
ruff over ci/nur, and the format-manifest check on repos.json)
runs here as tests; its second half (`nur update` + a full
nix-build) evaluates all 581 registered repositories over the
network and is an upstream-main operation, not a fork gate.

The lock file is accounted for exactly: repos.json.lock is
regenerated by upstream's update bot, and the two entries it
does not yet cover are pinned by name — when the bot locks
them, this suite goes red until the accounting is updated.

Run: python3 -m pytest tests/ -q
"""

from __future__ import annotations

import json
import shutil
import subprocess
from pathlib import Path

import pytest

REPO_ROOT = Path(__file__).resolve().parent.parent
SUBPROCESS_TIMEOUT_S = 300

# Registered in repos.json but not yet locked by upstream's
# update bot (measured 2026-10-16). Exact-set accounting.
UNLOCKED_REPOS = {'krebs', 'qompassai'}


def _validate_manifest(repos: dict[str, object]) -> list[str]:
    """Contract for the repos.json registry."""
    problems: list[str] = []
    names = list(repos)
    if names != sorted(names):
        problems.append('repos.json: entries are not in sorted order')
    for name, entry in repos.items():
        if not isinstance(entry, dict):
            problems.append(f'{name}: entry is not an object')
            continue
        url = entry.get('url')
        if not isinstance(url, str) or not url.startswith('https://'):
            problems.append(f'{name}: url is not an https URL: {url!r}')
        if not entry.get('github-contact'):
            problems.append(f'{name}: github-contact missing')
    return problems


def _load(name: str) -> dict[str, object]:
    data = json.loads((REPO_ROOT / name).read_text(encoding='utf-8'))
    assert isinstance(data, dict)
    repos = data['repos']
    assert isinstance(repos, dict)
    return repos


# --- Validation ---


def test_manifest_is_valid() -> None:
    repos = _load('repos.json')
    assert len(repos) >= 500, 'expected the full community registry'
    assert _validate_manifest(repos) == []


def test_qompassai_registration_is_intact() -> None:
    entry = _load('repos.json')['qompassai']
    assert isinstance(entry, dict)
    assert entry['url'] == 'https://github.com/qompassai/nur-packages'
    assert entry['branch'] == 'main'
    assert entry['github-contact'] == 'phaedrusflow'


def test_lock_file_accounting_is_exact() -> None:
    repos = _load('repos.json')
    locked = _load('repos.json.lock')
    assert set(locked) <= set(repos), 'lock names a repo the manifest dropped'
    assert set(repos) - set(locked) == UNLOCKED_REPOS
    for name, entry in locked.items():
        assert isinstance(entry, dict) and entry.get('rev') and entry.get('sha256'), (
            name
        )


def test_manifest_is_canonically_formatted(tmp_path: Path) -> None:
    """Upstream's format-manifest check, run in a scratch copy."""
    if shutil.which('nix') is None:
        pytest.skip('nix not installed')
    work = tmp_path / 'nur'
    shutil.copytree(
        REPO_ROOT, work, ignore=shutil.ignore_patterns('.git', 'tests', '__pycache__')
    )
    result = subprocess.run(
        ['nix', 'run', './ci#', '--', 'format-manifest'],
        cwd=work,
        capture_output=True,
        text=True,
        timeout=SUBPROCESS_TIMEOUT_S,
        check=False,
    )
    assert result.returncode == 0, result.stderr[-2000:]
    assert (work / 'repos.json').read_bytes() == (REPO_ROOT / 'repos.json').read_bytes()


def test_ci_tool_static_gates() -> None:
    """ci/test.sh's lint half: ruff, black, mypy over ci/nur."""
    ci_dir = REPO_ROOT / 'ci'
    commands = [
        ['ruff', 'check', 'nur'],
        ['black', '--check', '.'],
        ['mypy', 'nur'],
    ]
    for command in commands:
        if shutil.which(command[0]) is None:
            pytest.skip(f'{command[0]} not installed')
        result = subprocess.run(
            command,
            cwd=ci_dir,
            capture_output=True,
            text=True,
            timeout=SUBPROCESS_TIMEOUT_S,
            check=False,
        )
        assert result.returncode == 0, (
            f'{command}: {result.stdout[-1000:]}{result.stderr[-1000:]}'
        )


# --- Adversarial ---


def test_manifest_unsorted_is_rejected() -> None:
    repos = _load('repos.json')
    swapped = dict(reversed(list(repos.items())[:2]))
    swapped.update({k: v for k, v in list(repos.items())[2:]})
    assert _validate_manifest(swapped) != []


def test_manifest_non_https_url_is_rejected() -> None:
    repos = _load('repos.json')
    entry = dict(repos['qompassai'])  # type: ignore[arg-type]
    entry['url'] = 'git://github.com/qompassai/nur-packages'
    mutated = dict(repos)
    mutated['qompassai'] = entry
    assert _validate_manifest(mutated) != []


def test_manifest_missing_contact_is_rejected() -> None:
    repos = _load('repos.json')
    entry = dict(repos['qompassai'])  # type: ignore[arg-type]
    del entry['github-contact']
    mutated = dict(repos)
    mutated['qompassai'] = entry
    assert _validate_manifest(mutated) != []
